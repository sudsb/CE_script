/** @file LexCe.cxx
** Lexer for Cheat Engine scripts.
**
** A Cheat Engine script is a small multi-language document:
**   - Lua       trainer code (AutoAssemble strings, memory API, GUI)
**   - Auto Assembler  [ENABLE] / [DISABLE] sections, {$asm}
**   - C         inline {$ccode} blocks
**
** The mode is tracked per line (LexAccessor line state) and switched by
** [ENABLE]/[DISABLE] markers and {$lua}/{$asm}/{$ccode} directives, which is
** exactly what Cheat Engine's own script editor does.
**
** Style ids live in lexers_x\SciXLexer.h (SCE_CE_*).  The first twelve ids
** mirror SCE_LUA_* so existing theme files keep their colours.
*/

