#!/usr/bin/env python3
"""Generate Notepad3's Cheat Engine completion/keyword data.

The single source of truth is ``ce_edit/ce_edit/data/completions.json`` plus
the keyword sets in ``ce_edit/ce_edit/lexer.py``.  CE's own ``celua.txt`` is
parsed once by ``tools/gen_ce_lua_api.py`` into the checked-in
``ce_edit/ce_edit/data/celua_api.json`` and merged here as well.  Names that
CE registers only in its Pascal sources, plus the Lua 5.3 / CE class additions,
come from ``ce_edit/ce_edit/data/ce_source_api.json`` (generated by
``tools/gen_ce_source_api.py``).  Per-keyword usage notes live in
``ce_edit/ce_edit/data/keyword_docs.json`` and are emitted as a sparse,
name-sorted ``g_ceCompletionDocs[]`` table.  Run this script after editing any
of those files:

    python tools/gen_ce_keywords.py
"""

from __future__ import annotations

import json
import sys
from collections.abc import Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_C = ROOT / "src" / "StyleLexers" / "ce_completions_data.c"
OUT_H = ROOT / "src" / "StyleLexers" / "ce_completions_data.h"
LUA_API_FILE = ROOT / "ce_edit" / "ce_edit" / "data" / "celua_api.json"
SOURCE_API_FILE = ROOT / "ce_edit" / "ce_edit" / "data" / "ce_source_api.json"
DOCS_FILE = ROOT / "ce_edit" / "ce_edit" / "data" / "keyword_docs.json"

sys.path.insert(0, str(ROOT))

from ce_edit.ce_edit import completions, lexer  # noqa: E402


# Prefix glyph categories shown in the CE completion list.  These values are
# emitted into ce_completions_data.h so the C side and this generator share one
# numbering scheme; Scintilla uses them as registered AutoC image ids (?N).
KIND_NONE = 0
KIND_KEYWORD = 1
KIND_FUNCTION = 2
KIND_VARIABLE = 3
KIND_AA = 4
KIND_ASM = 5
KIND_TYPE = 6
KIND_CONSTANT = 7
KIND_SECTION = 8
KIND_COUNT = 9

