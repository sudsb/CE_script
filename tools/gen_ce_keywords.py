KIND_LABELS = (
    "",
    "关键字",
    "函数/API",
    "变量",
    "AA 命令",
    "汇编",
    "类型/类",
    "常量",
    "段标记",
)

# Chinese section labels of one keyword's usage notes.  The order here is the
# order shown in the completion detail pane and the CE reference panel; a doc
# entry may omit any of them.  These are the "angles" a reader needs: what it
# does, how to write it, a concrete example, its limits, related keywords,
# common mistakes and the Auto Assembler context.
DOC_FIELDS = ("功能", "语法", "示例", "约束", "相关", "易错", "AA 语境")


def completion_kind(category: str) -> int:
    """Return the AutoC glyph id for one catalogue category."""
    return KIND_BY_CATEGORY.get(category, KIND_FUNCTION)


def _c_string(value: str) -> str:
    """Return a C string literal body (without the surrounding quotes)."""
    result: list[str] = []
    for char in value:
        code = ord(char)
        if char == "\\":
            result.append("\\\\")
        elif char == '"':
            result.append('\\"')
        elif char == "\n":
            result.append("\\n")
        elif char == "\r":
            result.append("\\r")
        elif char == "\t":
            result.append("\\t")
        elif code < 0x20 or code == 0x7F:
            result.append(f"\\x{code:02X}")
        else:
            result.append(char)
    return "".join(result)


def _c_literal(value: str, indent: str = "    ", width: int = 100) -> str:
    """Format a long string as a sequence of adjacent C literals."""
    pieces: list[str] = []
    current = ""
    for char in value:
        escaped = _c_string(char)
        if current and len(current) + len(escaped) > width:
            pieces.append(current)
            current = ""
        current += escaped
    if current or not pieces:
        pieces.append(current)
    return "\n".join(f'{indent}"{piece}"' for piece in pieces)


def _keyword_string(words: Iterable[str]) -> str:
    return " ".join(sorted(word for word in words if word))


def _is_identifier(name: str) -> bool:
    if not name:
        return False
    if not (name[0].isalpha() or name[0] == "_"):
        return False
    return all(char.isalnum() or char == "_" for char in name[1:])


def _is_completion_name(name: str) -> bool:
    """Dotted receiver aliases (string.split) are valid completion items."""
    return all(_is_identifier(part) for part in name.split("."))


class ExtraEntry:
    """A completion entry that does not come from completions.json."""

    __slots__ = ("name", "signature", "category", "is_call")

    def __init__(self, name, signature, category, is_call):
        self.name = name
        self.signature = signature
        self.category = category
        self.is_call = is_call


def load_lua_api(path: Path | None = None) -> tuple[ExtraEntry, ...]:
    """Load a checked-in API catalogue (celua.txt or CE Pascal sources)."""
    try:
        payload = json.loads((path or LUA_API_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ()
    if not isinstance(payload, list):
        return ()
    entries: list[ExtraEntry] = []
    for raw in payload:
        if not isinstance(raw, dict):
            continue
        name = str(raw.get("name", ""))
        if not _is_completion_name(name):
            continue
        entries.append(
            ExtraEntry(
                name=name,
                signature=str(raw.get("signature", name)),
                category=str(raw.get("category", "CE Lua API")),
                is_call=bool(raw.get("is_call", "(" in str(raw.get("signature", "")))),
            )
        )
    return tuple(entries)


def load_source_api() -> tuple[ExtraEntry, ...]:
    """Load the CE Pascal-source / Lua 5.3 additions (checked in)."""
    return load_lua_api(SOURCE_API_FILE)


def _render_doc(fields: dict, name: str) -> str:
    """Join the present usage-note sections into one multiline UTF-8 string."""
    lines: list[str] = []
    for label in DOC_FIELDS:
        value = fields.get(label)
        if not isinstance(value, str) or not value.strip():
            continue
        text = value.strip().replace("{name}", name)
        lines.append(f"{label}：{text}")
    return "\n".join(lines)


def load_keyword_docs() -> dict[str, str]:
    """Load hand-written usage notes indexed by keyword name.

    ``docs`` holds per-keyword sections; ``groups`` applies one template to a
    list of related keywords (``{name}`` expands to the actual keyword).  Both
    are sourced from ce_edit, matching the completion/keyword single source.
    """
    try:
        payload = json.loads(DOCS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(payload, dict):
        return {}

    result: dict[str, str] = {}
    raw_docs = payload.get("docs", {})
    if isinstance(raw_docs, dict):
        for name, fields in raw_docs.items():
            if isinstance(name, str) and isinstance(fields, dict):
                rendered = _render_doc(fields, name)
                if rendered:
                    result[name] = rendered

    raw_groups = payload.get("groups", [])
    if isinstance(raw_groups, list):
        for group in raw_groups:
            if not isinstance(group, dict):
                continue
            names = group.get("names", [])
            if not isinstance(names, list):
                continue
            for name in names:
                if not isinstance(name, str) or name in result:
                    continue  # an explicit per-keyword note always wins
                rendered = _render_doc(group, name)
                if rendered:
                    result[name] = rendered
    return result


def _doc_lookup(entries: list, docs: dict[str, str]) -> list[tuple[str, str]]:
    """Every note is emitted (sorted for bsearch).

    Some documented keywords (AA directives such as ``aobscanmodule``) live only
    in the generated CE_KEYWORDS_* lexer sets and have no catalogue entry; they
    are still offered as completions, so their note must remain reachable.
    """
    return sorted(docs.items())


def merged_entries(keyword_groups: tuple[tuple[set[str], str, str], ...]) -> list:
    """Catalogue + celua.txt API + Pascal-source API + every lexer keyword set.

    The original catalogue wins on duplicate names: it carries the curated
    Chinese signatures the reference panel already shows.  Words that the lexer
    colours but the curated catalogue omits (Lua standard libraries, AA
    commands, inline-C keywords, x86 words) are appended as non-call entries,
    so highlighting and autocomplete never disagree about what is a keyword.
    """
    result: list = list(completions.load_completions())
    seen = {entry.name for entry in result}
    for entry in (*load_lua_api(), *load_source_api()):
        if entry.name not in seen:
            result.append(entry)
            seen.add(entry.name)
    for words, category, description in keyword_groups:
        for word in sorted(words):
            if word in seen or not _is_identifier(word):
                continue
            result.append(ExtraEntry(word, f"{word} -- {description}", category, False))
            seen.add(word)
    return result


def _registers() -> set[str]:
    names = {
        "rax", "rbx", "rcx", "rdx", "rsi", "rdi", "rbp", "rsp",
        "eax", "ebx", "ecx", "edx", "esi", "edi", "ebp", "esp",
        "ax", "bx", "cx", "dx", "si", "di", "bp", "sp",
        "al", "bl", "cl", "dl", "ah", "bh", "ch", "dh",
        "sil", "dil", "bpl", "spl",
        "cs", "ds", "es", "fs", "gs", "ss",
        "eip", "rip", "eflags", "rflags",
        "cr0", "cr2", "cr3", "cr4", "cr8",
    }
    names.update(f"r{i}" for i in range(8, 16))
    names.update(f"r{i}d" for i in range(8, 16))
    names.update(f"r{i}w" for i in range(8, 16))
    names.update(f"r{i}b" for i in range(8, 16))
    names.update(f"xmm{i}" for i in range(16))
    names.update(f"ymm{i}" for i in range(16))
    names.update(f"zmm{i}" for i in range(32))
    names.update(f"mm{i}" for i in range(8))
    names.update(f"st{i}" for i in range(8))
    names.update(f"dr{i}" for i in range(8))
    return names


def main() -> int:
    api = {name for name in completions.api_names() if _is_identifier(name)}
    for entry in (*load_lua_api(), *load_source_api()):
        if entry.is_call and _is_identifier(entry.name):
            api.add(entry.name)

    lua_words = (
        set(lexer.LUA_KW_CTRL)
        | set(lexer.LUA_KW_DECL)
        | set(lexer.LUA_KW_OP)
        | set(lexer.LUA_CONST)
        | set(lexer.LUA_LIBS)
        | set(lexer.CE_GLOBALS)
    )

    # Keep the two syntax groups aligned with ce_edit's lexer colours:
    # Auto Assembler commands/directives are WORD3, x86 instructions and
    # registers are WORD4.  Mixing mnemonics into the AA list makes "mov" and
    # "test" use the command colour, which looks wrong next to registers.
    aa_words = (
        set(lexer.AA_CMDS)
        | set(lexer.ASM_DIR)
        | set(lexer.ASM_SIZE)
        | set(lexer.WATCH_DIRECTIVES)
        | set(lexer.WATCH_TYPES)
        | set(lexer.WATCH_FORMATS)
        | set(lexer.C_KW)
        | set(lexer.C_TYPE)
    )

    type_categories = {
        "值类型",
        "CE 全局",
        "对象",
        "控件",
        "内存记录",
        "内存记录属性",
        "地址列表",
        "窗体",
        "Timer",
        "属性访问",
        "对象引用",
        "回调",
        "Pipe",
    }
    asm_words = (
        _registers()
        | set(lexer.ASM_JMP)
        | set(lexer.ASM_MNE)
        | {word for word in aa_words if word.lower().startswith("j")}
    )
    aa_words -= asm_words

    # Any word the lexer colours must also be offered by autocomplete.  Keep
    # the curated catalogue first and fill the gaps from the five keyword sets,
    # so a future lexer.py addition cannot silently lose its completion item.
    c_kw = set(lexer.C_KW)
    c_types = set(lexer.C_TYPE)
    keyword_groups = (
        (lua_words, "Lua 关键字", "Lua 关键字 / 标准库"),
        (aa_words - c_kw - c_types, "自动汇编", "Auto Assembler 命令 / 汇编指示"),
        (c_kw, "C 关键字", "内联 C 关键字"),
        (c_types, "C 类型", "内联 C 类型"),
        (asm_words, "汇编指令", "x86 汇编指令 / 寄存器"),
    )
    entries = merged_entries(keyword_groups)
    doc_rows = _doc_lookup(entries, load_keyword_docs())
    categories: list[str] = []
    for entry in entries:
        if entry.category not in categories:
            categories.append(entry.category)

    type_words = {
        entry.name
        for entry in entries
        if entry.category in type_categories and _is_identifier(entry.name)
    }

    api_words = {word for word in api if word not in type_words}

    lines: list[str] = []
    lines.append("// Generated by tools/gen_ce_keywords.py - do not edit by hand.")
    lines.append("// Sources: ce_edit/ce_edit/data/completions.json, celua_api.json, ce_source_api.json, lexer.py")
    lines.append("")
    lines.append('#include "ce_completions_data.h"')
    lines.append("")
    lines.append("const CE_COMPLETION_ENTRY g_ceCompletions[] = {")
    for entry in entries:
        call = "1" if entry.is_call else "0"
        kind = completion_kind(entry.category)
        lines.append(
            '    { "%s", "%s", "%s", %s, %d },'
            % (
                _c_string(entry.name),
                _c_string(entry.signature),
                _c_string(entry.category),
                call,
                kind,
            )
        )
    lines.append("};")
    lines.append("")
    lines.append(f"const int g_ceCompletionCount = {len(entries)};")
    lines.append("")
    lines.append("const char* const g_ceCategories[] = {")
    for category in categories:
        lines.append(f'    "{_c_string(category)}",')
    lines.append("};")
    lines.append("")
    lines.append(f"const int g_ceCategoryCount = {len(categories)};")
    lines.append("")
    lines.append("const char* const g_ceKindLabels[] = {")
    for label in KIND_LABELS:
        lines.append(f'    "{_c_string(label)}",')
    lines.append("};")
    lines.append("")
    lines.append("const char CE_KEYWORDS_LUA[] =")
    lines.append(_c_literal(_keyword_string(lua_words)) + ";")
    lines.append("")
    lines.append("const char CE_KEYWORDS_API[] =")
    lines.append(_c_literal(_keyword_string(api_words)) + ";")
    lines.append("")
    lines.append("const char CE_KEYWORDS_AA[] =")
    lines.append(_c_literal(_keyword_string(aa_words)) + ";")
    lines.append("")
    lines.append("const char CE_KEYWORDS_ASM[] =")
    lines.append(_c_literal(_keyword_string(asm_words)) + ";")
    lines.append("")
    lines.append("const char CE_KEYWORDS_TYPES[] =")
    lines.append(_c_literal(_keyword_string(type_words)) + ";")
    lines.append("")
    lines.append("const CE_COMPLETION_DOC g_ceCompletionDocs[] = {")
    for name, doc in doc_rows:
        lines.append(f'    {{ "{_c_string(name)}", "{_c_string(doc)}" }},')
    lines.append("};")
    lines.append("")
    lines.append(f"const int g_ceCompletionDocCount = {len(doc_rows)};")
    lines.append("")

    header = """// Generated by tools/gen_ce_keywords.py - do not edit by hand.
#pragma once

// Completion item categories.  Scintilla uses these as registered AutoC image
// ids: a list item is written as "word?N" and image N is drawn before it.
#define CE_KIND_NONE     0
#define CE_KIND_KEYWORD  1
#define CE_KIND_FUNCTION 2
#define CE_KIND_VARIABLE 3
#define CE_KIND_AA       4
#define CE_KIND_ASM      5
#define CE_KIND_TYPE     6
#define CE_KIND_CONSTANT 7
#define CE_KIND_SECTION  8
#define CE_KIND_COUNT    9

typedef struct CE_COMPLETION_ENTRY
{
    const char* name;
    const char* signature;
    const char* category;
    int isCall;
    int kind;
} CE_COMPLETION_ENTRY;

// Multiline (\\n separated) usage notes, name-sorted for binary search.  Only
// keywords with a hand-written note are present; everything else falls back to
// the "--" comment of its signature.
typedef struct CE_COMPLETION_DOC
{
    const char* name;
    const char* doc;
} CE_COMPLETION_DOC;

extern const CE_COMPLETION_ENTRY g_ceCompletions[];
extern const int g_ceCompletionCount;
extern const CE_COMPLETION_DOC g_ceCompletionDocs[];
extern const int g_ceCompletionDocCount;
extern const char* const g_ceCategories[];
extern const int g_ceCategoryCount;
extern const char* const g_ceKindLabels[];

extern const char CE_KEYWORDS_LUA[];
extern const char CE_KEYWORDS_API[];
extern const char CE_KEYWORDS_AA[];
extern const char CE_KEYWORDS_ASM[];
extern const char CE_KEYWORDS_TYPES[];
"""

    OUT_C.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8", newline="")
    OUT_H.write_text(header.replace("\n", "\r\n"), encoding="utf-8", newline="")
    print(f"wrote {OUT_C} ({len(entries)} entries, {len(categories)} categories)")
    print(f"wrote {OUT_H}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
